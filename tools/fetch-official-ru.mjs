#!/usr/bin/env node
/**
 * Where each Ellen G. White chapter is in its official Russian edition, in
 * the Ellen G. White Estate's free online reader (EGW Writings). Reads only
 * each Russian book's table of contents (chapter titles and the paragraph
 * each chapter starts at); no text is copied, since the Russian
 * translations are under copyright. Writes tools/commentary-official-ru.json,
 * which tools/build-commentary.mjs turns into links.
 *
 *   NODE_USE_ENV_PROXY=1 node tools/fetch-official-ru.mjs
 *
 * The book ids come from the reader's list of Russian books
 * (https://m.egwwritings.org/ru/folders/1216).
 */
import { writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { decodeEntities } from './lib/thml.mjs';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const SITE = 'https://m.egwwritings.org';

/** Our book id → the Russian edition's id in EGW Writings. */
export const RUSSIAN_EDITIONS = {
  'patriarchs-and-prophets': 1802,
  'prophets-and-kings': 1801,
  'desire-of-ages': 1798,
  'acts-of-the-apostles': 1785,
};

/**
 * A table of contents page → { title, chapters: { "4": { para, title }, … } }.
 * "Глава 4. Вам родился Спаситель" is chapter 4; an untitled-number entry
 * before chapter 1 ("Виноградник Божий") is the book's introduction.
 */
export function readContents(html, bookId) {
  const title = decodeEntities(/<title>([^<—]*)/.exec(html)?.[1] ?? '').trim();
  const chapters = {};
  const link = new RegExp(`<a[^>]+href="/ru/book/${bookId}\\.(\\d+)"[^>]*>([\\s\\S]*?)</a>`, 'g');
  for (const m of html.matchAll(link)) {
    const text = decodeEntities(m[2].replace(/<[^>]+>/g, ' ')).replace(/\s+/g, ' ').trim();
    if (!text || text === 'Read' || Number(m[1]) === 0) continue;
    const numbered = /^Глава (\d+)\.\s*(.*)$/.exec(text);
    if (numbered) chapters[numbered[1]] = { para: Number(m[1]), title: numbered[2] };
    else if (!Object.keys(chapters).length) chapters.introduction = { para: Number(m[1]), title: text };
  }
  return { title, chapters };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const out = {
    _comment: 'Generated by tools/fetch-official-ru.mjs: where each chapter starts in the official Russian edition in EGW Writings (book id, paragraph id), with the edition\'s chapter title. Links only; no text.',
    source: { name: 'EGW Writings', url: `${SITE}/ru` },
    works: {},
  };
  for (const [workId, bookId] of Object.entries(RUSSIAN_EDITIONS)) {
    const response = await fetch(`${SITE}/ru/book/${bookId}/toc`);
    if (!response.ok) throw new Error(`HTTP ${response.status} for book ${bookId}`);
    const { title, chapters } = readContents(await response.text(), bookId);
    out.works[workId] = { book: bookId, title, chapters };
    console.log(`${workId}: «${title}», ${Object.keys(chapters).length} chapters`);
  }
  await writeFile(join(ROOT, 'tools', 'commentary-official-ru.json'), `${JSON.stringify(out, null, 1)}\n`);
}
