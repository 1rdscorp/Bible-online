/**
 * Builds the drawing of the statue of Daniel 2 for the site:
 * tools/art/daniel-statue.svg → js/views/explore/statue-drawing.js.
 *
 *   node tools/build-statue.mjs
 *
 * The SVG names each part as a group (Head_gold, Chest_and_arms_silver,
 * Belly_and_thighs_bronze, Legs_iron, Feet_iron_and_clay, Stone), with a
 * Plinth and a Mountain_hidden that rises when the stone falls. The page
 * (js/views/explore/statue-figure.js) finds them by class and data-part,
 * so this marks them; it also prefixes every other id with "st-" (so they
 * can't clash with the map's on the same page), drops the title and size,
 * and refuses anything that could run or load (scripts, event attributes,
 * images, outside links). To change the drawing, replace the SVG, keep the
 * group names, and run this again; tests/explore.test.js checks the module
 * is up to date.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const SOURCE = join(ROOT, 'tools/art/daniel-statue.svg');
export const OUTPUT = join(ROOT, 'js/views/explore/statue-drawing.js');

// The SVG's group ids → what the page looks for.
const GROUPS = {
  Mountain_hidden: 'class="statue-mountain"',
  Plinth: 'class="statue-plinth"',
  Feet_iron_and_clay: 'class="statue-part" data-part="feet"',
  Legs_iron: 'class="statue-part" data-part="legs"',
  Belly_and_thighs_bronze: 'class="statue-part" data-part="belly"',
  Chest_and_arms_silver: 'class="statue-part" data-part="chest"',
  Head_gold: 'class="statue-part" data-part="head"',
  Stone: 'class="statue-part" data-part="stone"',
};

/** The SVG's contents (inside <svg>) ready for the page, and its viewBox. */
export function convertStatue(svgText) {
  const unsafe = svgText.match(/<script|<foreignObject|<image|<iframe|\son[a-z]+\s*=|javascript:|(?:xlink:)?href\s*=\s*"(?!#)|url\(\s*['"]?(?!#)|@import/i);
  if (unsafe) throw new Error(`The drawing contains "${unsafe[0]}": only shapes, gradients and clip paths are allowed.`);
  const svg = svgText.match(/<svg\b([^>]*)>([\s\S]*)<\/svg>/);
  if (!svg) throw new Error('No <svg> element.');
  const viewBox = svg[1].match(/viewBox="([^"]+)"/)?.[1];
  if (!viewBox) throw new Error('The <svg> needs a viewBox.');
  let body = svg[2]
    .replace(/<title>[\s\S]*?<\/title>|<desc>[\s\S]*?<\/desc>/g, '')
    .replace(/<g id="Mountain_hidden" display="none">/, '<g id="Mountain_hidden">');
  for (const [id, attributes] of Object.entries(GROUPS)) {
    const tag = new RegExp(`<g id="${id}">`);
    if (!tag.test(body)) throw new Error(`The drawing has no group <g id="${id}">.`);
    body = body.replace(tag, `<g ${attributes}>`);
  }
  // Every other id, and the references to it, gets the prefix.
  body = body.replace(/\bid="([^"]+)"/g, 'id="st-$1"').replace(/url\(#([^)]+)\)/g, 'url(#st-$1)').replace(/href="#([^"]+)"/g, 'href="#st-$1"');
  body = body.replace(/>\s+</g, '><').trim();
  // It goes into a template literal.
  if (/[`\\]|\$\{/.test(body)) throw new Error('The drawing contains a backtick, a backslash or "${".');
  return { viewBox, body };
}

export function statueModule(svgText) {
  const { viewBox, body } = convertStatue(svgText);
  return `// Generated by tools/build-statue.mjs from tools/art/daniel-statue.svg: don't edit by hand.
// The statue of Daniel 2, drawn on the same grid as its mountain and stone.

export const VIEW_BOX = '${viewBox}';

export const DRAWING = \`${body}\`;
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const source = statueModule(readFileSync(SOURCE, 'utf8'));
  writeFileSync(OUTPUT, source);
  console.log(`js/views/explore/statue-drawing.js: ${(source.length / 1024).toFixed(1)} KB`);
}
