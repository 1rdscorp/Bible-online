#!/usr/bin/env node
/**
 * Writes the list of the site's own files (the "app shell") into sw.js,
 * with a version made from their contents, so the service worker saves
 * exactly the current files for offline use and the browser picks up any
 * change.
 *
 *   node tools/build-offline.mjs          update sw.js
 *   node tools/build-offline.mjs --check  exit 1 if sw.js is out of date
 *
 * Run it after changing any HTML, CSS, JavaScript or icon file.
 * tests/offline.test.js fails while sw.js is out of date, as a reminder.
 */
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = fileURLToPath(new URL('..', import.meta.url));

const TOP_FILES = ['index.html', 'favicon.svg', 'manifest.webmanifest'];
const FOLDERS = [
  ['css', '.css'],
  ['js', '.js'],
  ['icons', '.png'],
];

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    return entry.isDirectory() ? walk(path) : [path];
  });
}

/** The app shell's files, relative to the site root, in a stable order. */
export function appFiles(root = ROOT) {
  const files = [...TOP_FILES];
  for (const [folder, extension] of FOLDERS) {
    files.push(
      ...walk(join(root, folder))
        .filter((path) => path.endsWith(extension))
        .map((path) => relative(root, path).split(sep).join('/'))
        .sort(),
    );
  }
  return files;
}

/** The generated block for sw.js: version (content hash) and file list. */
export function offlineBlock(root = ROOT) {
  const files = appFiles(root);
  const hash = createHash('sha256');
  for (const file of files) {
    hash.update(file).update('\0').update(readFileSync(join(root, file))).update('\0');
  }
  const version = hash.digest('hex').slice(0, 12);
  const list = files.map((file) => `  '${file}',`).join('\n');
  return `// <offline-files> generated by tools/build-offline.mjs: don't edit by hand
const VERSION = '${version}';
const APP_FILES = [
  './',
${list}
];
// </offline-files>`;
}

const BLOCK = /\/\/ <offline-files>[\s\S]*?\/\/ <\/offline-files>/;

export function currentBlock(root = ROOT) {
  return readFileSync(join(root, 'sw.js'), 'utf8').match(BLOCK)?.[0] ?? null;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const path = join(ROOT, 'sw.js');
  const source = readFileSync(path, 'utf8');
  const block = offlineBlock();
  if (process.argv.includes('--check')) {
    if (currentBlock() !== block) {
      console.error('sw.js is out of date: run node tools/build-offline.mjs');
      process.exit(1);
    }
    console.log('sw.js is up to date.');
  } else {
    writeFileSync(path, source.replace(BLOCK, block));
    console.log(`sw.js: ${appFiles().length} files, version ${block.match(/VERSION = '(\w+)'/)[1]}`);
  }
}
