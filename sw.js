const APP_CACHE = `bible-online-app-${VERSION}`;
const APP_PREFIX = 'bible-online-app-';
const DATA_CACHE = 'bible-online-data-v1';
// A manifest that hasn't answered by then comes from the saved copy, so a
// weak signal doesn't leave the app waiting.
const NETWORK_TIMEOUT = 4000;

const scopeUrl = (path) => new URL(path, self.registration.scope).href;
const appUrls = new Set(APP_FILES.map(scopeUrl));
const indexUrl = scopeUrl('index.html');

self.addEventListener('install', (event) => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(APP_CACHE);
      // cache: 'reload' skips the browser's HTTP cache, so the saved copy is
      // the version just published, not one from a few minutes ago.
      await cache.addAll(APP_FILES.map((path) => new Request(scopeUrl(path), { cache: 'reload' })));
      // The data lists too, so the very first offline start works.
      const data = await caches.open(DATA_CACHE);
      await Promise.all(
        ['data/translations.json', 'data/research.json'].map((path) =>
          fetch(scopeUrl(path), { cache: 'reload' })
            .then((response) => response.ok && data.put(scopeUrl(path), response))
            .catch(() => {}),
        ),
      );
    })(),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      // Earlier versions of the app shell; the saved Bible text stays.
      for (const name of await caches.keys()) {
        if (name.startsWith(APP_PREFIX) && name !== APP_CACHE) await caches.delete(name);
      }
      await self.clients.claim();
    })(),
  );
});

// The page asks for this when the reader taps "Reload" on the update message.
self.addEventListener('message', (event) => {
  if (event.data?.type === 'skip-waiting') self.skipWaiting();
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return; // audio, other sites
  if (url.searchParams.has('v')) return; // versioned data: translation-cache.js

  // The page itself (hash routes all load index.html).
  if (request.mode === 'navigate' && (url.href.split('#')[0] === scopeUrl('./') || url.href === indexUrl)) {
    event.respondWith(fromApp(indexUrl, request));
    return;
  }
  const bare = url.origin + url.pathname;
  if (appUrls.has(bare)) {
    event.respondWith(fromApp(bare, request));
    return;
  }
  if (url.pathname.endsWith('.json') && url.href.startsWith(scopeUrl('data/'))) {
    event.respondWith(networkFirst(request));
  }
  // Anything else goes to the network as usual.
});

async function fromApp(key, request) {
  const cache = await caches.open(APP_CACHE);
  return (await cache.match(key)) ?? fetch(request);
}

async function networkFirst(request) {
  const cache = await caches.open(DATA_CACHE);
  const network = fetch(request).then((response) => {
    if (response.ok) cache.put(request, response.clone()).catch(() => {});
    return response;
  });
  const saved = cache.match(request);
  try {
    // The network's answer, unless it's slow and a saved copy exists.
    return await Promise.race([
      network,
      new Promise((resolve, reject) =>
        setTimeout(async () => ((await saved) ? resolve(await saved) : reject(new Error('timeout'))), NETWORK_TIMEOUT),
      ),
    ]);
  } catch (error) {
    return (await saved) ?? (error.message === 'timeout' ? network : Promise.reject(error));
  }
}
