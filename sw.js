/**
 * Service worker: lets the site open and run without an internet connection,
 * and install as an app on a phone.
 *
 * - The site itself (the "app shell": index.html, CSS, JavaScript, icons) is
 *   saved when the worker installs and always served from that copy, so the
 *   app opens instantly, online or not. The list and its version below are
 *   written by tools/build-offline.mjs; a change to any of those files
 *   changes the version, the browser notices the new worker, and the page
 *   offers to reload into it (js/offline.js).
 * - The two lists of data files (data/translations.json, data/research.json)
 *   come from the network when it answers, so new translations and data
 *   appear as soon as they're published, and from the saved copy when it
 *   doesn't.
 * - The Bible text and study data (files with ?v=<version>) are saved by the
 *   page itself (js/providers/translation-cache.js) the first time they're
 *   opened; this worker leaves them alone.
 * - Other sites (the audio from predanie.ru, Yandex Translate) are never
 *   touched: they work when there's a connection, as before.
 */

